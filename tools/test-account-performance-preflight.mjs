#!/usr/bin/env node

import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import test from 'node:test';

import { prepareAccountPerformancePreflight } from './prepare-account-performance-preflight.mjs';

function sha256Json(value) {
  return crypto.createHash('sha256').update(JSON.stringify(value)).digest('hex');
}

function context({ status = 'historical-stale', stale = true } = {}) {
  const works = Array.from({ length: 7 }, (_, index) => ({
    videoKey: `video-${index + 1}`,
    title: `作品${index + 1}`,
    metrics: { plays: (index + 1) * 100 }
  }));
  const sourceReceipt = {
    acceptedRunId: 'accepted-run',
    collectedAt: '2026-08-11T14:00:00.000Z',
    sourceSha256: 'a'.repeat(64),
    publishedWorkCount: works.length
  };
  sourceReceipt.receiptSha256 = sha256Json(sourceReceipt);
  return {
    schemaVersion: 'douyin-account-performance-context/1.0',
    status,
    sourceReceipt,
    accountDataState: {
      stale,
      boundary: stale ? '最近采集失败，不得冒充当前。' : '当前官方快照存在统计延迟。'
    },
    coverage: {
      allAcceptedHistoryUsed: true,
      allPublishedWorksIncluded: true,
      publishedWorkCount: works.length,
      acceptedRunCount: 2,
      acceptedHistoryCoverageHours: 24
    },
    accountBaseline: { workCount: works.length, totalPlays: 2800 },
    contentTypeBaselines: [{ contentType: '视频', workCount: works.length }],
    recentSix: works.slice(0, 6),
    allPublishedWorks: works,
    acceptedHistory: {
      status: 'ready',
      snapshots: [{ runId: 'old' }, { runId: 'accepted-run' }],
      periods: { day: { status: 'ready' } },
      latestVideoChanges: [],
      anomalies: [],
      boundary: '增量不自动证明因果。'
    },
    interpretationBoundary: {
      descriptiveFactsOnly: true,
      causalLessonsRequireHumanConfirmation: true,
      staleDataCannotBeDescribedAsCurrent: true
    }
  };
}

function learningCard() {
  return {
    schema_version: 1,
    type: 'douyin-account-performance-learning',
    status: 'current',
    snapshot_at: '2026-08-10T22:52:59+08:00',
    lessons: [{ id: 'lesson:opening:test', status: 'active' }],
    active_content_contract: {
      opening: { title_answer_by_second_max: 15 },
      duration: { single_core_problem_required: true },
      metrics: { required_metrics: ['five_second_completion_rate'] }
    }
  };
}

async function fixture(t, contextValue = context()) {
  const root = await mkdtemp(path.join(os.tmpdir(), 'koubo-performance-preflight-'));
  t.after(() => rm(root, { recursive: true, force: true }));
  const contextPath = path.join(root, 'context.json');
  const learningCardPath = path.join(root, 'learning-card.json');
  const output = path.join(root, 'receipts/task.json');
  const snapshotDirectory = path.join(root, 'snapshots');
  await writeFile(contextPath, `${JSON.stringify(contextValue, null, 2)}\n`);
  await writeFile(learningCardPath, `${JSON.stringify(learningCard(), null, 2)}\n`);
  return { root, contextPath, learningCardPath, output, snapshotDirectory };
}

test('自动预检绑定全量账号事实、当前学习卡与任务ID', async (t) => {
  const files = await fixture(t);
  const { receipt, outputPath } = await prepareAccountPerformancePreflight({
    ...files,
    taskId: 'task-auto-data-1',
    requiresCurrent: false
  });

  assert.equal(receipt.taskId, 'task-auto-data-1');
  assert.equal(receipt.status, 'ready-historical-stale');
  assert.equal(receipt.accountContext.publishedWorkCount, 7);
  assert.equal(receipt.accountContext.acceptedRunCount, 2);
  assert.equal(receipt.accountContext.allAcceptedHistoryUsed, true);
  assert.equal(receipt.accountContext.allPublishedWorksIncluded, true);
  assert.equal(receipt.accountContext.recentSixCount, 6);
  assert.equal(receipt.automaticUseContract.descriptiveFactsLoadedAutomatically, true);
  assert.equal(receipt.automaticUseContract.causalLessonsNotAutoGenerated, true);
  assert.equal(receipt.automaticReference.accountBaseline.workCount, 7);
  assert.equal(receipt.automaticReference.contentTypeBaselines.length, 1);
  assert.equal(receipt.automaticReference.recentSix.length, 6);
  assert.equal(receipt.automaticReference.acceptedHistorySignals.latestVideoChanges.length, 0);
  assert.deepEqual(receipt.learningCard.activeLessonIds, ['lesson:opening:test']);
  assert.equal(JSON.parse(await readFile(outputPath, 'utf8')).taskId, 'task-auto-data-1');
  assert.match(receipt.accountContext.snapshotSha256, /^[a-f0-9]{64}$/);
  assert.equal(
    crypto.createHash('sha256').update(await readFile(receipt.accountContext.snapshotPath)).digest('hex'),
    receipt.accountContext.snapshotSha256
  );
});

test('要求当前数据时，过期官方历史必须阻断', async (t) => {
  const files = await fixture(t);
  await assert.rejects(
    prepareAccountPerformancePreflight({
      ...files,
      taskId: 'task-requires-current',
      requiresCurrent: true
    }),
    /最近官方采集已过期或失败/
  );
});

test('缺少全量历史覆盖时不得生成回执', async (t) => {
  const incomplete = context();
  incomplete.coverage.allAcceptedHistoryUsed = false;
  const files = await fixture(t, incomplete);
  await assert.rejects(
    prepareAccountPerformancePreflight({
      ...files,
      taskId: 'task-incomplete-data',
      requiresCurrent: false
    }),
    /没有覆盖全部已接纳历史/
  );
});
